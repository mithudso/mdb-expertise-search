#!/usr/bin/env python3
"""Regenerate docs/high_signal_file_index.json and docs/codebase-overview.md (code only, not corpus)."""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PURPOSE = {
    "mdbx/corpus.py": "Corpus discovery, classification, chunking",
    "mdbx/embed.py": "Ollama embedding client",
    "mdbx/index.py": "SQLite schema + keyword/semantic index builds",
    "mdbx/search.py": "Keyword, semantic, hybrid ranking",
    "mdbx/cli.py": "mdbx command entry point",
    "mdbx/tui.py": "Textual TUI",
    "mdbx/__init__.py": "Package version",
    "tests/test_core.py": "Core unit tests",
    "tests/test_tui.py": "TUI pilot test",
    "scripts/sync_corpus.sh": "Rebuild corpus from local skills + reindex",
    "scripts/gen_file_index.py": "Regenerate this index",
    "scripts/check_doc_indexes.py": "Validate index paths",
    "pyproject.toml": "Packaging, deps, tool config",
    "README.md": "Overview and quick start",
}


def tracked() -> list[str]:
    out = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return [p for p in out.splitlines() if not p.startswith("corpus/")]


def main() -> None:
    files = tracked()
    entries = [
        {"path": p, "purpose": PURPOSE.get(p, "docs/config"), "bytes": (ROOT / p).stat().st_size}
        for p in files
        if (ROOT / p).is_file()
    ]
    (ROOT / "docs" / "high_signal_file_index.json").write_text(json.dumps(entries, indent=2) + "\n")
    by_dir: dict[str, list[str]] = {}
    for e in entries:
        by_dir.setdefault(str(Path(e["path"]).parent), []).append(e["path"])
    lines = ["# Codebase overview", "", "Generated by `scripts/gen_file_index.py`. `corpus/` is data, not code.", ""]
    for d in sorted(by_dir):
        lines.append(f"## {d}/" if d != "." else "## (root)")
        for p in sorted(by_dir[d]):
            lines.append(f"- `{p}` — {PURPOSE.get(p, 'docs/config')}")
        lines.append("")
    (ROOT / "docs" / "codebase-overview.md").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
