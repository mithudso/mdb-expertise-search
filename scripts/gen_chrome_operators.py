#!/usr/bin/env python3
"""Write the MQL operator table for the Chrome extension from mdbx/mql/operators.py.

Emits two files from the same data so the extension never hand-copies the table:

* ``editors/chrome/lib/operators.json`` — plain data (for tooling and inspection).
* ``editors/chrome/lib/operators-data.js`` — ``export default {...}``, the file ``lib/operators.js``
  imports (JSON import attributes are not reliable in every browser and test runner).

    python scripts/gen_chrome_operators.py            # regenerate
    python scripts/gen_chrome_operators.py --check    # exit 1 if either file is stale
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from mdbx.mql import operators as ops

LIB = ROOT / "editors" / "chrome" / "lib"
JSON_OUT = LIB / "operators.json"
JS_OUT = LIB / "operators-data.js"


def table() -> dict:
    """The operator table as plain data; operator order is the table order (it drives suggest())."""
    return {
        "operators": [
            {"name": o.name, "cats": sorted(o.cats), "arg": o.arg, "doc": o.doc}
            for o in ops.OPERATORS.values()
        ],
        "variables": dict(ops.VARIABLES),
        "sets": {
            "FIRST_STAGE_ONLY": sorted(ops.FIRST_STAGE_ONLY),
            "LAST_STAGE_ONLY": sorted(ops.LAST_STAGE_ONLY),
            "NOT_IN_FACET": sorted(ops.NOT_IN_FACET),
            "STAGES": sorted(ops.STAGES),
            "UPDATE_OPS": sorted(ops.UPDATE_OPS),
            "UPDATE_PIPELINE_STAGES": sorted(ops.UPDATE_PIPELINE_STAGES),
        },
    }


def render() -> tuple[str, str]:
    body = json.dumps(table(), indent=1, ensure_ascii=False, sort_keys=True)
    js = ("// GENERATED by scripts/gen_chrome_operators.py from mdbx/mql/operators.py — do not edit.\n"
          f"export default {body};\n")
    return body + "\n", js


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    want = dict(zip((JSON_OUT, JS_OUT), render(), strict=True))
    stale = [p.name for p, text in want.items()
             if not p.is_file() or p.read_text(encoding="utf-8") != text]
    if a.check:
        if stale:
            print("stale (run scripts/gen_chrome_operators.py):", ", ".join(stale))
            return 1
        return 0
    for p, text in want.items():
        p.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
