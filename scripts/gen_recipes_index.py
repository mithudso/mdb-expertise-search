#!/usr/bin/env python3
"""Regenerate docs/RECIPES.md from the frontmatter of corpus/recipes/*.md."""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from mdbx import recipes

GROUPS = [
    ("Sharding", ["shard-a-collection", "reshard-a-collection", "convert-replica-set-to-sharded-cluster"]),
    ("Networking", ["atlas-private-link", "atlas-network-peering", "private-connectivity-troubleshooting"]),
    ("Upgrades", ["upgrade-atlas-cluster-major-version", "upgrade-self-managed-replica-set",
                  "upgrade-self-managed-sharded-cluster", "fcv-and-rollback-plan"]),
    ("Backup, restore, DR, migration", ["restore-atlas-snapshot-or-pitr", "self-managed-backup-and-restore",
                                        "disaster-recovery-failover-test", "migrate-with-mongosync"]),
    ("Indexes, performance, search, lifecycle", ["build-index-safely-in-production", "diagnose-slow-query",
                                                 "create-atlas-search-index", "create-atlas-vector-search-index",
                                                 "set-up-ttl-and-online-archive"]),
    ("Security and operations", ["create-database-users-and-roles", "configure-workforce-sso-oidc",
                                 "enable-client-side-or-queryable-encryption", "set-up-alerts-and-monitoring",
                                 "resize-and-autoscale-atlas-cluster"]),
]


def main() -> None:
    items = {r.name: r for r in recipes.load(ROOT / "corpus")}
    placed: set[str] = set()
    lines = [
        "# Recipes",
        "",
        "Step-by-step runbooks for common MongoDB / Atlas operations, written from the corpus. Generated by",
        "`scripts/gen_recipes_index.py`. Read one with `mdbx recipe <name>`, search them with",
        "`mdbx search -k recipe \"...\"`, or press `Ctrl+R` in `mdbx tui`.",
        "",
        "Each recipe cites its corpus sources and marks anything the corpus could not confirm with",
        "**\"Verify in the current MongoDB docs:\"** — treat those steps as unverified until checked.",
        "",
    ]
    for title, names in GROUPS:
        rows = [items[n] for n in names if n in items]
        if not rows:
            continue
        lines += [f"## {title}", "", "| Recipe | Applies to | Summary |", "|---|---|---|"]
        for r in rows:
            placed.add(r.name)
            lines.append(f"| [`{r.name}`](../corpus/recipes/{r.name}.md) | {', '.join(r.applies_to) or '-'} | {r.summary} |")
        lines.append("")
    extra = [r for n, r in items.items() if n not in placed]
    if extra:
        lines += ["## Other", "", "| Recipe | Applies to | Summary |", "|---|---|---|"]
        lines += [f"| [`{r.name}`](../corpus/recipes/{r.name}.md) | {', '.join(r.applies_to) or '-'} | {r.summary} |" for r in extra]
        lines.append("")
    (ROOT / "docs" / "RECIPES.md").write_text("\n".join(lines))
    print(f"wrote docs/RECIPES.md ({len(items)} recipes)")


if __name__ == "__main__":
    main()
